# -*- coding: utf-8 -*-
"""
Белгiлердi есептеу модулiн тексеру.
Модульдің дұрыстығын тексеру үшін күтілетін мән дәл белгілі болуы шарт,
ал нақты сигналда ол белгісіз. Сондықтан кіріске статистикалары формуламен
есептелетін үш эталондық сигнал беріледі.
"""
import io, time
import numpy as np
from features import mean_, std_, range_, slope_, zcr_, extract, normalize, WIN, N_CH

R = io.open('test_features_report.txt', 'w', encoding='utf-8')
def w(s=''):
    R.write(s + '\n')

N = WIN
i = np.arange(N, dtype=float)

# эталондық сигналдар
# 1. Сызықтық өсу: x = a*i + b
a, b = 0.02, 0.1
ramp = a * i + b
ramp_exp = {
    'Mean':  a * (N - 1) / 2.0 + b,
    'STD':   a * np.sqrt((N * N - 1) / 12.0),
    'Range': a * (N - 1),
    'Slope': a,
    'ZCR':   1.0 / (N - 1),          # монотонды сигнал орташаны бір рет қияды
}

# 2. Тұрақты сигнал
const = np.full(N, 0.73)
const_exp = {'Mean': 0.73, 'STD': 0.0, 'Range': 0.0, 'Slope': 0.0, 'ZCR': 0.0}

# 3. Синус, терезеге дәл екі период сыяды, амплитудасы A
A = 0.5
sine = A * np.sin(2 * np.pi * 2 * i / N)
sine_exp = {
    'Mean':  0.0,
    'STD':   A / np.sqrt(2.0),
    'Range': None,                   # дискреттеуге тәуелді, төменде бөлек
    'Slope': None,
    # Синустың нөлдері t = 0; 12,5; 25; 37,5 нүктелерінде. Қиылысу көрші екі
    # есептеудің аралығында тіркеледі, ал t = 0 нөлі бірінші есептеудің дәл
    # өзіне түседі, демек ешбір аралықтың ішінде жатпайды. Сондықтан
    # тіркелетін қиылысу саны төртеу емес, үшеу.
    'ZCR':   3.0 / (N - 1),
}

w('1-БЛОК. СТАТИСТИКАЛАРДЫ АНАЛИТИКАЛЫҚ МӘНМЕН САЛЫСТЫРУ')
w('=' * 72)
w('%-22s %-8s %-16s %-16s %s' % ('Сигнал', 'Стат.', 'Модуль', 'Формула', 'Айырма'))

FUN = {'Mean': mean_, 'STD': std_, 'Range': range_, 'Slope': slope_, 'ZCR': zcr_}
maxerr = 0.0
nchk = 0
for name, sig, exp in (('сызықтық өсу', ramp, ramp_exp),
                       ('тұрақты', const, const_exp),
                       ('синус, 2 период', sine, sine_exp)):
    for st in ('Mean', 'STD', 'Range', 'Slope', 'ZCR'):
        if exp[st] is None:
            continue
        got = FUN[st](sig)
        err = abs(got - exp[st])
        maxerr = max(maxerr, err)
        nchk += 1
        w('%-22s %-8s %-16.9f %-16.9f %.2e' % (name, st, got, exp[st], err))
w('')
w('Тексерiлген мән саны: %d' % nchk)
w('Ең үлкен абсолют айырма: %.2e' % maxerr)
w('Қос дәлдiктегi машиналық эпсилон: %.2e' % np.finfo(float).eps)
w('')

# Slope таңбасы
w('2-БЛОК. SLOPE СТАТИСТИКАСЫНЫҢ ТАҢБАНЫ САҚТАУЫ')
w('=' * 72)
w('3.2-тармақтағы тұжырым: «бару» мен «келу» жұбын ажырататын қасиет -')
w('Slope-тың өзгерiс бағытын таңбамен беруi. Тексеру: бiр сигнал және оның')
w('уақыт бойынша аударылған нұсқасы.')
w('')
rev = ramp[::-1].copy()
w('%-28s %12s %12s %12s %12s' % ('Сигнал', 'Mean', 'STD', 'Range', 'Slope'))
for nm, s in (('тура жүрiс (өсу)', ramp), ('керi жүрiс (кему)', rev)):
    w('%-28s %12.6f %12.6f %12.6f %+12.6f' % (nm, mean_(s), std_(s), range_(s), slope_(s)))
w('')
w('Mean, STD, Range үш статистикасы да екi сигнал үшiн бiрдей.')
w('Айырмашылықты тек Slope бередi: %+.4f және %+.4f.' % (slope_(ramp), slope_(rev)))
w('')

# RMS артықтығы
w('3-БЛОК. RMS СТАТИСТИКАСЫНЫҢ АРТЫҚ ЕКЕНIН ТЕКСЕРУ')
w('=' * 72)
w('3.2-тармақтағы тұжырым: RMS шамасы Mean мен STD-дан шығарылады,')
w('яғни RMS^2 = Mean^2 + STD^2. Кездейсоқ 10 000 терезеде тексерiлдi.')
rng = np.random.default_rng(20260914)
worst = 0.0
for _ in range(10000):
    x = rng.normal(0.5, 0.2, N)
    rms = np.sqrt(np.mean(x ** 2))
    pred = np.sqrt(mean_(x) ** 2 + std_(x) ** 2)
    worst = max(worst, abs(rms - pred))
w('Ең үлкен алшақтық: %.2e' % worst)
w('Қорытынды: RMS жаңа ақпарат қоспайды, сондықтан бесiншi статистика')
w('ретiнде Slope алынды.')
w('')

# өлшемділік
w('4-БЛОК. БЕЛГIЛЕР ВЕКТОРЫНЫҢ ӨЛШЕМДIЛIГI ЖӘНЕ ЕСЕПТЕУ УАҚЫТЫ')
w('=' * 72)
win = rng.normal(0.0, 1.0, (WIN, N_CH))
v = extract(win)
w('Терезе пiшiмi: %d есептеу x %d арна' % (WIN, N_CH))
w('Белгiлер векторының өлшемдiлiгi: %d' % v.size)
w('Күтiлген мән 17 x 5 = %d, сәйкес: %s' % (17 * 5, 'иә' if v.size == 85 else 'жоқ'))
w('')

M = 2000
t0 = time.perf_counter()
for _ in range(M):
    extract(win)
t1 = time.perf_counter()
per_ms = (t1 - t0) / M * 1000.0
w('%d терезеде орташа есептеу уақыты: %.3f мс (ноутбук, Python)' % (M, per_ms))
w('Терезе қадамы 10 есептеу = 0,2 с, демек бюджеттiң %.2f %%.' % (per_ms / 200.0 * 100))
w('')

# қалыпқа келтіру
w('5-БЛОК. ҚАЛЫПҚА КЕЛТIРУ ТҰРАҚТЫЛАРЫН ТЕКСЕРУ')
w('=' * 72)
raw = np.zeros((WIN, N_CH))
raw[:, 0:5] = np.linspace(300, 1400, WIN)[:, None]     # иілу арналары, АЦП отсчёттары
raw[:, 5:8] = 8.0                                      # акселерометр, шектік мән +8g
raw[:, 8:11] = 1000.0                                  # гироскоп, шектік мән
raw[:, 11:14] = -8.0
raw[:, 14:17] = -1000.0
nz = normalize(raw, [300] * 5, [1400] * 5)
w('Иiлу арналары    : ең кiшi %.3f, ең үлкен %.3f' % (nz[:, 0].min(), nz[:, 0].max()))
w('Акселерометр +8g : %.3f' % nz[0, 5])
w('Гироскоп +1000   : %.3f' % nz[0, 8])
w('Акселерометр -8g : %.3f' % nz[0, 11])
w('Гироскоп -1000   : %.3f' % nz[0, 14])
w('')
w('Диапазонның шектiк мәндерi [-1; 1] аралығына түстi, демек')
w('бөлгiш тұрақтылары 2.4-тармақта таңдалған диапазондарға сәйкес.')

R.close()
print('ok')
